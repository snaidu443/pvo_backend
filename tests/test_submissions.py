ADMIN, EDITOR, VIEWER = auth('admin@example.test'), auth('editor@example.test'), auth('viewer@example.test')
URL = '/api/assets/submissions'


def pdf(tag: str = 'a') -> bytes:
    return f'%PDF-1.7 synthetic {tag}'.encode()


def ooxml(folder: str, tag: str = 'a', macro: bool = False) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, 'w') as z:
        z.writestr('[Content_Types].xml', '<Types/>')
        z.writestr(f'{folder}/main.xml', f'<synthetic>{tag}</synthetic>')
        if macro:
            z.writestr(f'{folder}/vbaProject.bin', b'macro')
    return buf.getvalue()


def meta(*doc_types: str, **extra) -> str:
    return json.dumps({'name': 'TEST-200', 'area': 'Oncology', 'modality': 'Small molecule', 'jcaInsights': 'No',
                       'documents': [{'docType': t} for t in doc_types], **extra})


def submit(client, files, metadata, headers=EDITOR):
    parts = [('files', (name, body, 'application/octet-stream')) for name, body in files]
    return client.post(URL, data={'metadata': metadata}, files=parts, headers=headers)


def standard(client):
    files = [('CDP_FY27.pptx', ooxml('ppt', 'cdp1')), ('CDP_appendix.pdf', pdf('cdp2')), ('Forecast_v3.xlsx', ooxml('xl', 'fc'))]
    return submit(client, files, meta('CDP', 'CDP', 'Forecast'))


def storage():
    return app.dependency_overrides[get_storage]()


def scan(key: str, verdict: str):
    with app.dependency_overrides[get_session_factory]()() as db:
        return apply_scan_result(db, storage(), key, verdict)


def stored_keys(asset_id: str) -> list[str]:
    folder = storage().root / 'assets' / asset_id
    return sorted(f'assets/{asset_id}/{p.name}' for p in folder.iterdir()) if folder.exists() else []


def all_stored_files() -> list:
    return [p for p in storage().root.rglob('*') if p.is_file()]


# ---------------- happy path

def test_submission_saves_everything_and_waits_for_the_scan(client):
    r = standard(client)
    assert r.status_code == 202, r.text
    out = r.json()
    asset_id, job_id = out['assetId'], out['jobId']
    assert re.fullmatch(r'PVO-[0-9A-F]{8}', asset_id)  # generated by the server
    assert out['asset']['assetCode'] == 'TEST-200' and out['asset']['context']['modality'] == 'Small molecule'
    assert [d['type'] for d in out['documents']] == ['CDP', 'CDP', 'Forecast']
    assert {d['scanStatus'] for d in out['documents']} == {'pending_scan'}
    assert 'storage' not in r.text and 'assets/' not in r.text  # keys and paths never leave the server

    keys = stored_keys(asset_id)
    assert len(keys) == 3 and all(re.fullmatch(r'assets/PVO-[0-9A-F]{8}/[0-9a-f]{32}\.(pptx|pdf|xlsx)', k) for k in keys)

    mine = next(a for a in client.get('/api/assets', headers=EDITOR).json() if a['id'] == asset_id)
    assert mine['workflowStatus'] == 'extracting'
    job = client.get(f'/api/assets/{asset_id}/extract/{job_id}', headers=EDITOR).json()
    assert job['status'] == 'waiting_for_scan'  # nothing is read before the malware scan
    assert client.get(f'/api/assets/{asset_id}/extract/latest', headers=EDITOR).json()['jobId'] == job_id

    doc_id = out['documents'][0]['id']
    assert client.get(f'/api/documents/{doc_id}/download', headers=EDITOR).status_code == 409  # not scanned yet

    assert scan(keys[0], 'NO_THREATS_FOUND') is None and scan(keys[1], 'NO_THREATS_FOUND') is None
    resume = scan(keys[2], 'NO_THREATS_FOUND')
    assert resume == job_id
    from app.extraction import run_job
    run_job(app.dependency_overrides[get_session_factory](), storage(), resume)

    job = client.get(f'/api/assets/{asset_id}/extract/{job_id}', headers=EDITOR).json()
    assert job['status'] == 'done' and job['error'] is None
    mine = next(a for a in client.get('/api/assets', headers=EDITOR).json() if a['id'] == asset_id)
    assert mine['workflowStatus'] == 'inputs_review'

    first = client.get(f'/api/documents/{doc_id}/download', headers=EDITOR)
    assert first.status_code == 200 and first.content == ooxml('ppt', 'cdp1')
    assert first.headers['content-disposition'].startswith('attachment;')
    assert first.headers['content-type'].startswith('application/vnd.openxmlformats-officedocument.presentationml')


def test_submitted_asset_can_be_saved_back_and_deleted(client):
    out = standard(client).json()
    asset_id = out['assetId']
    asset = next(a for a in client.get('/api/assets', headers=EDITOR).json() if a['id'] == asset_id)
    asset['workflowStatus'] = 'active'  # server-owned: accepted but ignored
    saved = client.put(f'/api/assets/{asset_id}', json=asset, headers=EDITOR)
    assert saved.status_code == 200 and saved.json()['workflowStatus'] == 'extracting'
    assert client.delete(f'/api/assets/{asset_id}', headers=EDITOR).status_code == 204
    assert stored_keys(asset_id) == []  # the asset's files and folder are removed


def test_infected_file_is_removed_and_failed_extraction_can_be_retried(client):
    out = submit(client, [('CI_Q3.pdf', pdf('ci'))], meta('CI')).json()
    asset_id, (key,) = out['assetId'], stored_keys(out['assetId'])
    job_id = scan(key, 'THREATS_FOUND')
    assert stored_keys(asset_id) == []  # infected file deleted at once
    from app.extraction import run_job
    run_job(app.dependency_overrides[get_session_factory](), storage(), job_id)
    job = client.get(f'/api/assets/{asset_id}/extract/{job_id}', headers=EDITOR).json()
    assert job['status'] == 'failed' and 'malware scan' in job['error']
    assert next(a for a in client.get('/api/assets', headers=EDITOR).json() if a['id'] == asset_id)['workflowStatus'] == 'extraction_failed'

    assert client.post(f'/api/assets/{asset_id}/extract/retry', headers=VIEWER).status_code in (403, 404)
    again = client.post(f'/api/assets/{asset_id}/extract/retry', headers=EDITOR)
    assert again.status_code == 202 and again.json()['jobId'] != job_id


def test_unknown_scan_verdict_is_never_clean(client):
    out = submit(client, [('CI_Q3.pdf', pdf('ci'))], meta('CI')).json()
    (key,) = stored_keys(out['assetId'])
    scan(key, 'SOMETHING_NEW')
    docs = [d for d in client.get('/api/documents', headers=EDITOR).json() if d['assetId'] == out['assetId']]
    assert docs[0]['scanStatus'] == 'failed'


