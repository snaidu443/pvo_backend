@pytest.mark.parametrize('files, metadata, code', [
    ([('CI.pdf', pdf())], meta('CI', 'CDP'), 422),                                    # counts differ
    ([('CI.xlsx', ooxml('xl'))], meta('CI'), 422),                                    # format not allowed in the CI slot
    ([('CDP.pdf', b'not really a pdf')], meta('CDP'), 422),                           # content does not match .pdf
    ([('Protocol.docx', ooxml('xl'))], meta('Protocol'), 422),                        # zip, but not a Word file
    ([('Protocol.docx', ooxml('word', macro=True))], meta('Protocol'), 422),          # macros
    ([('run.exe', b'MZ')], meta('CDP'), 422),                                         # not an allowed type
    ([('a.pdf', pdf('x')), ('b.pdf', pdf('x'))], meta('CDP', 'CDP'), 422),            # same file twice
    ([(f'{i}.pdf', pdf(str(i))) for i in range(6)], meta(*['CI'] * 6), 422),         # more than 5 in one slot
    ([('CI.pdf', pdf())], meta('CI', modality='Gene editing'), 422),                  # not a form option
    ([('CI.pdf', pdf())], meta('TPP'), 422),                                          # unknown document type
    ([('CI.pdf', pdf())], meta('CI', name='DEMO-1'), 409),                            # name already used
    ([('CI.pdf', b'')], meta('CI'), 422),                                             # empty file
])
def test_rejected_submissions_store_nothing(client, files, metadata, code):
    before = len(client.get('/api/assets', headers=ADMIN).json())
    r = submit(client, files, metadata)
    assert r.status_code == code, r.text
    assert len(client.get('/api/assets', headers=ADMIN).json()) == before
    assert all_stored_files() == []


