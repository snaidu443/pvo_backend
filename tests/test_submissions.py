def test_only_writers_with_access_can_submit_or_see_jobs(client):
    assert submit(client, [('CI.pdf', pdf())], meta('CI'), headers=VIEWER).status_code == 403
    assert submit(client, [('CI.pdf', pdf())], meta('CI'), headers={}).status_code == 401
    out = standard(client).json()
    url = f"/api/assets/{out['assetId']}/extract/{out['jobId']}"
    assert client.get(url, headers=VIEWER).status_code == 404  # no access to this asset: looks like it does not exist
    assert client.get(url, headers=ADMIN).status_code == 200
    assert client.get(f"/api/assets/DEMO-1/extract/{out['jobId']}", headers=EDITOR).status_code == 404  # job of another asset


