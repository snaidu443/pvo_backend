class FakeS3:
    """Stands in for the boto3 S3 client (no AWS calls in tests)."""

    def __init__(self, length_delta: int = 0):
        self.objects, self.calls, self.length_delta = {}, [], length_delta

    def upload_fileobj(self, stream, bucket, key, ExtraArgs):  # noqa: N803 - boto3 argument name
        self.calls.append(('put', bucket, key, ExtraArgs))
        self.objects[key] = stream.read()

    def head_object(self, Bucket, Key):  # noqa: N803
        return {'ContentLength': len(self.objects[Key]) + self.length_delta, 'VersionId': 'v1'}

    def get_object(self, Bucket, Key):  # noqa: N803
        return {'Body': io.BytesIO(self.objects[Key])}

    def delete_object(self, Bucket, Key):  # noqa: N803
        self.calls.append(('delete', Bucket, Key))
        self.objects.pop(Key, None)


def test_s3_storage_encrypts_and_prefixes_every_object():
    s3 = FakeS3()
    store = S3FileStorage('pvo-docs-dev', 'pvo/dev/', 'alias/pvo-docs-dev', s3)
    obj = store.save(io.BytesIO(pdf()), asset_id='PVO-1A2B3C4D', ext='pdf', content_type='application/pdf', max_bytes=1024)
    (_, bucket, key, extra), = s3.calls
    assert bucket == 'pvo-docs-dev' and key == f'pvo/dev/{obj.key}' and obj.version_id == 'v1'
    assert extra['ServerSideEncryption'] == 'aws:kms' and extra['SSEKMSKeyId'] == 'alias/pvo-docs-dev'
    assert extra['ChecksumAlgorithm'] == 'SHA256' and extra['ContentType'] == 'application/pdf'
    assert store.open(obj.key).read() == pdf()
    store.delete(obj.key)
    assert s3.objects == {}


def test_s3_upload_with_wrong_size_is_removed():
    s3 = FakeS3(length_delta=1)
    store = S3FileStorage('pvo-docs-dev', 'pvo/dev', 'alias/pvo-docs-dev', s3)
    with pytest.raises(StorageError):
        store.save(io.BytesIO(pdf()), asset_id='PVO-1A2B3C4D', ext='pdf', content_type='application/pdf', max_bytes=1024)
    assert s3.objects == {}


